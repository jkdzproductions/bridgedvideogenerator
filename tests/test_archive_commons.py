def _page(index, *, width=3000, height=2000, mime="image/jpeg", license_="pd", short="Public domain",
          copyrighted="False", original="1864-09-27", with_thumb=True, extra_meta=None):
    info = {
        "width": width, "height": height, "mime": mime,
        "url": f"https://upload.wikimedia.org/original/{index}.jpg",
        "descriptionurl": f"https://commons.wikimedia.org/wiki/File:{index}.jpg",
        "extmetadata": {
            "ObjectName": {"value": f"Photo <i>{index}</i>"},
            "Artist": {"value": "<a href='x'>Matthew Brady</a>"},
            "DateTimeOriginal": {"value": original},
            "License": {"value": license_}, "LicenseShortName": {"value": short},
            "Copyrighted": {"value": copyrighted},
        },
    }
    for key, value in (extra_meta or {}).items():
        info["extmetadata"][key] = {"value": value}
    if copyrighted is None:
        del info["extmetadata"]["Copyrighted"]
    if with_thumb:
        info.update({"thumburl": f"https://upload.wikimedia.org/thumb/{index}.jpg", "thumbwidth": 1920,
                     "thumbheight": 1280})
    return {"pageid": index, "index": index, "title": f"File:{index}.jpg", "imageinfo": [info]}


def _payload(*pages):
    return {"query": {"pages": {str(p["pageid"]): p for p in pages}}}


def test_a_public_domain_photo_becomes_a_candidate_with_its_source_and_rights():
    [c] = parse_commons_response(_payload(_page(1)))

    assert c == ArchiveCandidate(
        source="commons", item_id="1", kind="photo", title="Photo 1", year=1864, creator="Matthew Brady",
        rights="Public domain", page_url="https://commons.wikimedia.org/wiki/File:1.jpg",
        media_url="https://upload.wikimedia.org/thumb/1.jpg", thumbnail_url="https://upload.wikimedia.org/thumb/1.jpg",
        width=1920, height=1280)
    assert c.display_id == "commons:1"


def test_results_keep_the_search_order_from_the_index_field():
    candidates = parse_commons_response(_payload(_page(3), _page(1), _page(2)))

    assert [c.item_id for c in candidates] == ["1", "2", "3"]


def test_a_photo_smaller_than_the_1920_thumbnail_is_used_at_its_original_url():
    [c] = parse_commons_response(_payload(_page(1, width=1500, height=1000)))

    assert c.media_url == "https://upload.wikimedia.org/original/1.jpg"
    assert (c.width, c.height) == (1500, 1000)


@pytest.mark.parametrize("kwargs", [
    {"license_": "cc-by-sa-4.0", "short": "CC BY-SA 4.0"},     # attribution licenses are not public domain
    {"license_": "cc-by-4.0", "short": "CC BY 4.0"},
    {"license_": "", "short": ""},                              # unclear rights are dropped
    {"copyrighted": "True"},                                    # explicitly copyrighted
    {"mime": "image/svg+xml"}, {"mime": "image/tiff"},          # not a photo the renderer takes
    {"width": 800, "height": 600},                              # too small for a full-frame photo
])
def test_unclear_restricted_or_unusable_photos_never_become_candidates(kwargs):
    assert parse_commons_response(_payload(_page(1, **kwargs))) == []


def test_a_public_domain_file_with_no_copyrighted_field_is_accepted():
    assert len(parse_commons_response(_payload(_page(1, copyrighted=None)))) == 1


def test_a_wide_photo_without_a_thumbnail_falls_back_to_the_original():
    [c] = parse_commons_response(_payload(_page(1, width=3000, height=2000, with_thumb=False)))

    assert c.media_url == "https://upload.wikimedia.org/original/1.jpg"
    assert (c.width, c.height) == (3000, 2000)


def test_cc0_counts_as_open():
    assert len(parse_commons_response(_payload(_page(1, license_="cc0", short="CC0")))) == 1


def test_a_page_without_imageinfo_is_skipped():
    assert parse_commons_response(_payload({"pageid": 9, "index": 1, "title": "File:x.jpg"})) == []


def test_a_known_year_outside_the_range_is_dropped_and_an_unknown_year_is_dropped_too():
    pages = _payload(_page(1, original="1864"), _page(2, original="1990"), _page(3, original=""))

    kept = parse_commons_response(pages, year_range=(1850, 1880))

    assert [c.item_id for c in kept] == ["1"]


