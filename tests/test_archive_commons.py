def test_search_sends_a_bitmap_search_with_the_project_user_agent(monkeypatch):
    seen = {}

    class Resp:
        status_code = 200
        def json(self): return _payload(_page(1))

    def fake_get(url, params=None, headers=None, timeout=None, **kw):
        seen.update(url=url, params=params, headers=headers)
        return Resp()

    monkeypatch.setattr(types_mod.requests, "get", fake_get)

    result = search_commons_photos("atlanta railroad 1860s", limit=7)

    assert len(result) == 1
    assert seen["url"] == "https://commons.wikimedia.org/w/api.php"
    assert seen["params"]["gsrsearch"] == "atlanta railroad 1860s filetype:bitmap"
    assert seen["params"]["gsrlimit"] == 7 and seen["params"]["gsrnamespace"] == 6
    assert seen["headers"]["User-Agent"] == USER_AGENT == "VersedVideoGenerator/0.1"


