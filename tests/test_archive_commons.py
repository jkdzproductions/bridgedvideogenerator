def test_network_failures_become_archive_errors_for_both_helpers(monkeypatch, tmp_path):
    def boom(*a, **k): raise types_mod.requests.Timeout("timed out")

    monkeypatch.setattr(types_mod.requests, "get", boom)

    with pytest.raises(ArchiveError, match="timed out"):
        get_json("https://example.org/api", {})
    with pytest.raises(ArchiveError, match="timed out"):
        fetch_to_file("https://example.org/x.jpg", str(tmp_path / "x.jpg"))


def test_fetch_to_file_closes_the_response(monkeypatch, tmp_path):
    closed = []

    class Good:
        status_code = 200
        def iter_content(self, chunk_size): return iter([b"a"])
        def close(self): closed.append(True)

    monkeypatch.setattr(types_mod.requests, "get", lambda *a, **k: Good())
    fetch_to_file("https://example.org/x.jpg", str(tmp_path / "x.jpg"))
    assert closed == [True]


def test_fetch_to_file_writes_the_bytes_and_removes_a_partial_file_on_failure(monkeypatch, tmp_path):
    class Good:
        status_code = 200
        def iter_content(self, chunk_size): return iter([b"ab", b"cd"])
        def close(self): pass

    monkeypatch.setattr(types_mod.requests, "get", lambda *a, **k: Good())
    dest = tmp_path / "sub" / "x.jpg"
    assert fetch_to_file("https://example.org/x.jpg", str(dest)) == str(dest)
    assert dest.read_bytes() == b"abcd"

    class Bad:
        status_code = 404
        def iter_content(self, chunk_size): return iter([])
        def close(self): pass

    monkeypatch.setattr(types_mod.requests, "get", lambda *a, **k: Bad())
    with pytest.raises(ArchiveError, match="404"):
        fetch_to_file("https://example.org/missing.jpg", str(tmp_path / "y.jpg"))
    assert not (tmp_path / "y.jpg").exists()


